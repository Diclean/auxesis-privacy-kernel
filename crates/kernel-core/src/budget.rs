//! Per-agent daily budgets over recorded provider usage.
//!
//! Usage is recorded by resource dimension ([`UsageKind`]: input tokens,
//! output tokens, cents) in the store; [`Budgets`] carries the daily caps
//! from the `[budgets]` section of `config.toml`; and [`BudgetGuard`]
//! decides — before a provider call — whether an agent may spend more today.
//!
//! The guard never touches the store directly: it talks to a
//! [`UsageLedger`] for the day's totals and an [`AuditSink`] for the
//! `budget.denied` events. The app implements both over its own store, which
//! keeps this crate dependency-free of SQLite and trivial to test with
//! in-memory fakes.
//!
//! Configuration shape (top-level caps apply to every agent, `[budgets.agents.*]`
//! overrides field by field). Unknown keys are rejected so a typo like
//! `token_in` can never silently disable a cap:
//!
//! ```toml
//! [budgets.default]
//! tokens_in = 2_000_000
//! tokens_out = 400_000
//! usd_cents = 500
//!
//! [budgets.agents.main]
//! tokens_in = 20_000
//! ```
//!
//! When `[budgets]` is absent — or the `[budgets.default]` table exists but
//! is empty, or a field is absent/zero — the conservative defaults apply per
//! field: a fresh **and an upgraded** install is capped, not unlimited. An
//! explicit `unlimited = true` is the only opt-out (the daemon logs it
//! loudly on every turn).

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fmt;
use std::time::Duration;
use thiserror::Error;

/// Serde helper: omit `false` flags from a serialized config.
fn is_false(value: &bool) -> bool {
    !*value
}

/// Unit marker for token amounts derived from text length instead of
/// provider-reported `usage` (providers that do not report usage).
pub const ESTIMATED_UNIT: &str = "tokens_est";

/// Default daily input-token cap for every agent when the config says nothing.
///
/// Calibration (H-03): the owner chose 2,000,000 input tokens/day — the
/// previous 100,000 was hit during ordinary daily use. The shape of the cap
/// (reservation, latch, warning, explicit `unlimited` opt-out) is unchanged.
pub const DEFAULT_DAILY_TOKENS_IN: u64 = 2_000_000;

/// Default daily output-token cap for every agent when the config says nothing.
///
/// Calibration (H-03): raised with the input cap (400,000 output tokens/day).
pub const DEFAULT_DAILY_TOKENS_OUT: u64 = 400_000;

/// Default daily spend cap (cents) for every agent when the config says nothing.
///
/// Calibration (H-03): 500 cents/day (the previous 50 cents/day was reached
/// during ordinary daily use).
pub const DEFAULT_DAILY_USD_CENTS: u64 = 500;

/// Default daily **connector-call** cap for every agent when the config says
/// nothing.
///
/// Connector calls do not spend provider tokens; they are a separate resource
/// dimension (the `connector_calls` [`UsageKind`]) metered by the connector
/// layer. Like the provider kinds, an unset or `0` field still falls back to a
/// conservative daily cap so a runaway tool loop cannot call a remote service
/// unbounded. The provider budget guard and the spend-reservation ledger are
/// deliberately unaware of this kind (they iterate [`UsageKind::PROVIDER`]),
/// so adding it cannot gate an ordinary provider call.
pub const DEFAULT_DAILY_CONNECTOR_CALLS: u64 = 500;

/// Fraction of a cap (8/10 = 80 %) at which a `budget.warning` event is
/// emitted, once per kind/day, before the day latches closed.
pub const WARNING_NUMERATOR: u64 = 8;
/// Denominator of [`WARNING_NUMERATOR`].
pub const WARNING_DENOMINATOR: u64 = 10;

/// The usage line at which `limit` starts warning (used by the store's
/// settle path and kept here so every layer warns at the same point).
pub fn warning_threshold(limit: u64) -> u64 {
    (limit as u128 * WARNING_NUMERATOR as u128 / WARNING_DENOMINATOR as u128) as u64
}

/// Conservative daily cap for one kind, applied when a config does not say
/// otherwise (absent field, empty `[budgets.default]` table, or a `0`
/// placeholder). This keeps an **existing** installation capped after an
/// upgrade: `serde(default)` only fires for a missing key, never for an
/// empty table an old config already carries.
pub(crate) fn conservative_limit(kind: UsageKind) -> u64 {
    match kind {
        UsageKind::TokensIn => DEFAULT_DAILY_TOKENS_IN,
        UsageKind::TokensOut => DEFAULT_DAILY_TOKENS_OUT,
        UsageKind::UsdCents => DEFAULT_DAILY_USD_CENTS,
        UsageKind::ConnectorCalls => DEFAULT_DAILY_CONNECTOR_CALLS,
    }
}

/// Resource dimension a daily budget can cap.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum UsageKind {
    /// Tokens sent to the provider.
    TokensIn,
    /// Tokens generated by the provider.
    TokensOut,
    /// Money spent, in cents.
    UsdCents,
    /// Remote connector (MCP) tool calls. Accounted per agent in the `usage`
    /// table like the provider kinds, but reserved and settled by the
    /// connector meter, never by the provider spend reservation.
    ///
    /// The daily cap for this kind is enforced from the S3 connector layer
    /// only: the provider budget guard and the reservation ledger never gate
    /// on it (see [`UsageKind::PROVIDER`]).
    ConnectorCalls,
}

impl UsageKind {
    /// All kinds, in the order budgets and config round-trips enumerate them.
    ///
    /// This is the *configuration* set, not the set the provider budget guard
    /// enforces: see [`UsageKind::PROVIDER`] for that. `ConnectorCalls` is
    /// appended after `UsdCents` (S2b) so a config round-trip keeps every
    /// pre-existing kind untouched.
    pub const ALL: [UsageKind; 4] = [
        Self::TokensIn,
        Self::TokensOut,
        Self::UsdCents,
        Self::ConnectorCalls,
    ];

    /// The kinds the provider [`BudgetGuard`] and [`ReservationLedger`] check.
    ///
    /// Kept separate from [`UsageKind::ALL`] on purpose: the provider spend
    /// path carries no connector-call amount, so folding `ConnectorCalls` into
    /// its loops would either index past the provider arrays or let an
    /// exhausted connector cap deny a provider call. The connector layer meters
    /// its own kind.
    pub const PROVIDER: [UsageKind; 3] = [Self::TokensIn, Self::TokensOut, Self::UsdCents];

    /// Stable string used in the store and audit payloads.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::TokensIn => "tokens_in",
            Self::TokensOut => "tokens_out",
            Self::UsdCents => "usd_cents",
            Self::ConnectorCalls => "connector_calls",
        }
    }

    /// Unit label for a recorded amount of this kind.
    pub fn unit(self) -> &'static str {
        match self {
            Self::TokensIn | Self::TokensOut => "tokens",
            Self::UsdCents => "cents",
            Self::ConnectorCalls => "calls",
        }
    }

    /// Parse the stable string back.
    pub fn parse(raw: &str) -> Option<Self> {
        match raw {
            "tokens_in" => Some(Self::TokensIn),
            "tokens_out" => Some(Self::TokensOut),
            "usd_cents" => Some(Self::UsdCents),
            "connector_calls" => Some(Self::ConnectorCalls),
            _ => None,
        }
    }
}

/// How long an in-flight spend reservation stays active before it is treated
/// as abandoned (crashed process) and ignored by the cap check.
///
/// A reservation only covers one provider call, so this can be generous: the
/// only cost of a large TTL is that a crash mid-call keeps the reservation
/// counted until it expires.
///
/// It must also outlive the longest *stream* one call can run: the
/// OpenAI-compatible adapter bounds a stream at
/// `DEFAULT_TIMEOUT × STREAM_TOTAL_TIMEOUT_FACTOR` (120 s × 10 = 20 min with
/// the defaults), and a reservation that expires while the provider is still
/// generating lets a concurrent turn reserve the same headroom (I-02). 30
/// minutes leaves a 10-minute margin over that ceiling; the engine asserts
/// the relation in `the app's engine`.
pub const RESERVATION_TTL: Duration = Duration::from_secs(1800);

impl fmt::Display for UsageKind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// Spend totals for one agent over one day.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct UsageTotals {
    /// Tokens sent to the provider.
    pub tokens_in: u64,
    /// Tokens generated by the provider.
    pub tokens_out: u64,
    /// Money spent, in cents.
    pub usd_cents: u64,
}

impl UsageTotals {
    /// Total for one kind carried by this struct.
    ///
    /// [`UsageKind::ConnectorCalls`] is deliberately not carried here (it is
    /// accounted in the `usage` table and summed by the connector layer), so it
    /// reads as `0` rather than panicking. Provider loops iterate
    /// [`UsageKind::PROVIDER`], not [`UsageKind::ALL`].
    pub fn get(&self, kind: UsageKind) -> u64 {
        match kind {
            UsageKind::TokensIn => self.tokens_in,
            UsageKind::TokensOut => self.tokens_out,
            UsageKind::UsdCents => self.usd_cents,
            UsageKind::ConnectorCalls => 0,
        }
    }

    /// True when nothing was spent at all.
    pub fn is_zero(&self) -> bool {
        *self == Self::default()
    }
}

/// Daily caps for one agent. Unset fields mean "no cap".
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct BudgetCaps {
    /// Maximum input tokens per day.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tokens_in: Option<u64>,
    /// Maximum output tokens per day.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tokens_out: Option<u64>,
    /// Maximum spend in cents per day.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub usd_cents: Option<u64>,
    /// Maximum connector (MCP) tool calls per day (S2b). An unset or `0`
    /// field falls back to [`DEFAULT_DAILY_CONNECTOR_CALLS`] like the provider
    /// kinds; the connector meter is the only consumer.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub connector_calls: Option<u64>,
    /// Explicit opt-out: **no** daily cap for this agent. Logged loudly when
    /// used; the default config never sets it.
    #[serde(skip_serializing_if = "is_false")]
    pub unlimited: bool,
}

impl BudgetCaps {
    /// The conservative caps a fresh install runs under: a runaway turn loop
    /// cannot spend more than a few cents a day until the owner raises them
    /// in `[budgets]`.
    pub fn conservative_default() -> Self {
        Self {
            tokens_in: Some(DEFAULT_DAILY_TOKENS_IN),
            tokens_out: Some(DEFAULT_DAILY_TOKENS_OUT),
            usd_cents: Some(DEFAULT_DAILY_USD_CENTS),
            // Left unset so a fresh config.toml gains no new key; the effective
            // cap still comes from `conservative_limit` via `limit()`.
            connector_calls: None,
            unlimited: false,
        }
    }

    /// Cap for one kind: the configured value, or the conservative default
    /// when the field is absent or a `0` placeholder. Only an explicit
    /// `unlimited = true` removes the cap entirely.
    pub fn limit(&self, kind: UsageKind) -> Option<u64> {
        if self.unlimited {
            return None;
        }
        let configured = match kind {
            UsageKind::TokensIn => self.tokens_in,
            UsageKind::TokensOut => self.tokens_out,
            UsageKind::UsdCents => self.usd_cents,
            UsageKind::ConnectorCalls => self.connector_calls,
        };
        Some(
            configured
                .filter(|value| *value > 0)
                .unwrap_or_else(|| conservative_limit(kind)),
        )
    }

    /// True when no kind has an explicit value in this set. Note that an
    /// "unset" set still *enforces* the conservative defaults (E-17): only
    /// [`Self::unlimited`] turns enforcement off.
    pub fn is_unset(&self) -> bool {
        self.tokens_in.is_none()
            && self.tokens_out.is_none()
            && self.usd_cents.is_none()
            && self.connector_calls.is_none()
    }

    /// True only for the explicit opt-out. An all-unset cap set is **not**
    /// unlimited: it enforces the conservative defaults (P1-1), so the only
    /// way to opt out is to write `unlimited = true` (which the daemon logs
    /// loudly).
    pub fn is_unlimited(&self) -> bool {
        self.unlimited
    }

    /// `self` with `overrides` applied on top, field by field.
    pub fn merged_with(&self, overrides: &BudgetCaps) -> BudgetCaps {
        BudgetCaps {
            tokens_in: overrides.tokens_in.or(self.tokens_in),
            tokens_out: overrides.tokens_out.or(self.tokens_out),
            usd_cents: overrides.usd_cents.or(self.usd_cents),
            connector_calls: overrides.connector_calls.or(self.connector_calls),
            unlimited: self.unlimited || overrides.unlimited,
        }
    }
}

/// The `[budgets]` section: defaults plus per-agent overrides.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Budgets {
    /// Caps that apply to every agent unless overridden. Missing or partial
    /// sections keep the conservative defaults (see
    /// [`BudgetCaps::conservative_default`]) — "no cap" is no longer the
    /// silent default.
    #[serde(default = "BudgetCaps::conservative_default")]
    pub default: BudgetCaps,
    /// Per-agent overrides; fields left unset fall back to `default`. Read from
    /// the legacy `[budgets.dots]` table too.
    #[serde(skip_serializing_if = "HashMap::is_empty", alias = "dots")]
    pub agents: HashMap<String, BudgetCaps>,
}

impl Default for Budgets {
    fn default() -> Self {
        Self {
            default: BudgetCaps::conservative_default(),
            agents: HashMap::new(),
        }
    }
}

impl Budgets {
    /// Effective caps for `agent`: the agent's overrides merged onto the defaults.
    pub fn caps_for(&self, agent: &str) -> BudgetCaps {
        match self.agents.get(agent) {
            Some(overrides) => self.default.merged_with(overrides),
            None => self.default,
        }
    }

    /// True when no agent has any cap configured.
    pub fn is_unset(&self) -> bool {
        self.default.is_unset() && self.agents.values().all(BudgetCaps::is_unset)
    }
}

/// Price of one model, in **whole cents per million tokens**.
///
/// Integer cents keep the ledger's `usd_cents` arithmetic exact; per-call
/// costs are rounded **up** to the next cent so a stream of small calls can
/// never slip under the money cap.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct ModelPrice {
    /// Cents charged per million input tokens.
    pub input_cents_per_million: u64,
    /// Cents charged per million output tokens.
    pub output_cents_per_million: u64,
}

/// Per-model price table (`[prices.models.<model>]` in `config.toml`).
///
/// Used to turn provider-reported tokens into recorded `usd_cents` spend so
/// the daily money cap can bind. A model the table does not know records no
/// money (the engine logs one notice: token caps are the effective ones).
/// The built-in defaults cover the models this installation uses; the owner
/// can override or extend them in config.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct PriceTable {
    /// Model id (`ProviderConfig::model`) to price.
    pub models: HashMap<String, ModelPrice>,
}

impl Default for PriceTable {
    /// Built-in prices for the models this installation is documented to use
    /// (cents per million tokens).
    fn default() -> Self {
        let mut models = HashMap::new();
        for (model, input, output) in [
            // DeepSeek via opencode-go / OpenCode Zen (no retention).
            ("deepseek-v4-flash", 14, 28),
            ("deepseek-v4.1-flash", 14, 28),
            ("deepseek-v4-pro", 174, 348),
            // DeepSeek direct list price (the pre-migration config).
            ("deepseek-flash", 22, 66),
            // Other families seen in the fleet.
            ("minimax-m3", 30, 120),
            ("gpt-6-luna", 10, 50),
        ] {
            models.insert(
                model.to_string(),
                ModelPrice {
                    input_cents_per_million: input,
                    output_cents_per_million: output,
                },
            );
        }
        Self { models }
    }
}

impl PriceTable {
    /// Price for `model`, when the table knows it.
    pub fn price(&self, model: &str) -> Option<&ModelPrice> {
        self.models.get(model)
    }

    /// Cost of one call in cents, rounded up; `0` when the model is unknown
    /// (the engine logs a one-time notice: the `usd_cents` cap cannot bind
    /// and the token caps are the effective ones).
    pub fn usd_cents_for(&self, model: Option<&str>, tokens_in: u64, tokens_out: u64) -> u64 {
        let Some(price) = model.and_then(|model| self.models.get(model)) else {
            return 0;
        };
        let numerator = tokens_in as u128 * price.input_cents_per_million as u128
            + tokens_out as u128 * price.output_cents_per_million as u128;
        numerator.div_ceil(1_000_000).min(u64::MAX as u128) as u64
    }
}

/// Failures reported by a [`UsageLedger`] or an [`AuditSink`].
#[derive(Debug, Error, PartialEq, Eq)]
pub enum BudgetError {
    /// The day's usage could not be read; the guard fails closed.
    #[error("usage ledger unavailable: {0}")]
    Ledger(String),
    /// The denial could not be audited; the denial still stands.
    #[error("audit sink unavailable: {0}")]
    Audit(String),
}

/// Day totals for an agent, as seen by the guard.
pub trait UsageLedger {
    /// Total spend for `agent` on the local day `day` (`YYYY-MM-DD`).
    fn day_totals(&self, agent: &str, day: &str) -> Result<UsageTotals, BudgetError>;
}

/// Destination for `budget.denied` audit events.
pub trait AuditSink {
    /// Append an audit event with a JSON payload.
    fn audit(&self, kind: &str, payload: &str) -> Result<(), BudgetError>;
}

/// Why the guard denied a call.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DenialReason {
    /// A daily cap is reached (or exceeded).
    CapExceeded {
        /// The capped resource.
        kind: UsageKind,
        /// Spend recorded so far today.
        spent: u64,
        /// Spend reserved by calls still in flight today.
        reserved: u64,
        /// Configured daily cap.
        limit: u64,
    },
    /// Usage could not be read, so the guard failed closed.
    LedgerUnavailable {
        /// Underlying ledger error.
        message: String,
    },
    /// A completed call reached or crossed a daily cap, so the day is latched
    /// closed: every later call for this agent/day is denied until the next
    /// local day. Written by [`ReservationLedger::settle`] when a provider
    /// settles above its admitted reservation (B-01R).
    FailClosed {
        /// Why the day was closed (which kind reached its cap, and where).
        message: String,
    },
}

/// One denial, with enough context for the user and the audit log.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Denial {
    /// Agent the call was made for.
    pub agent: String,
    /// Local day the budget applies to (`YYYY-MM-DD`).
    pub day: String,
    /// Structured cause.
    pub reason: DenialReason,
    /// Set when writing the `budget.denied` audit event failed.
    pub audit_error: Option<String>,
}

impl Denial {
    /// Human-readable one-liner.
    pub fn reason_text(&self) -> String {
        let base = match &self.reason {
            DenialReason::CapExceeded {
                kind,
                spent,
                reserved,
                limit,
            } => {
                if *reserved > 0 {
                    format!(
                        "agent `{}` reached its daily {kind} budget \
                         ({spent} spent + {reserved} reserved / {limit} on {})",
                        self.agent, self.day
                    )
                } else {
                    format!(
                        "agent `{}` reached its daily {kind} budget ({spent}/{limit} on {})",
                        self.agent, self.day
                    )
                }
            }
            DenialReason::LedgerUnavailable { message } => format!(
                "agent `{}`: cannot verify the daily budget ({message}); failing closed",
                self.agent
            ),
            DenialReason::FailClosed { message } => format!(
                "agent `{}`: {message}; failing closed for the rest of {}",
                self.agent, self.day
            ),
        };
        match &self.audit_error {
            Some(err) => format!("{base} (audit failed: {err})"),
            None => base,
        }
    }

    /// JSON payload written to the store as a `budget.denied` event.
    pub fn audit_payload(&self) -> String {
        let mut payload = serde_json::json!({
            "agent": self.agent,
            "day": self.day,
            "reason": self.reason_text(),
        });
        match &self.reason {
            DenialReason::CapExceeded {
                kind,
                spent,
                reserved,
                limit,
            } => {
                payload["kind"] = serde_json::json!(kind.as_str());
                payload["spent"] = serde_json::json!(spent);
                payload["reserved"] = serde_json::json!(reserved);
                payload["limit"] = serde_json::json!(limit);
            }
            DenialReason::LedgerUnavailable { message } => {
                payload["error"] = serde_json::json!(message);
            }
            DenialReason::FailClosed { message } => {
                payload["fail_closed"] = serde_json::json!(true);
                payload["message"] = serde_json::json!(message);
            }
        }
        payload.to_string()
    }
}

/// Outcome of a budget check.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Decision {
    /// The agent is within its daily caps.
    Allowed,
    /// The agent must not make another provider call today.
    Denied(Denial),
}

impl Decision {
    /// True for [`Decision::Allowed`].
    pub fn is_allowed(&self) -> bool {
        matches!(self, Decision::Allowed)
    }

    /// The denial, when there is one.
    pub fn denial(&self) -> Option<&Denial> {
        match self {
            Decision::Allowed => None,
            Decision::Denied(denial) => Some(denial),
        }
    }
}

/// What one provider call actually consumed, per direction.
///
/// `*_estimated` marks a direction the provider did not report (the amount is
/// derived from text length and recorded with [`ESTIMATED_UNIT`]).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct UsageActual {
    /// Tokens sent to the provider.
    pub tokens_in: u64,
    /// True when `tokens_in` is an estimate, not provider-reported.
    pub tokens_in_estimated: bool,
    /// Tokens generated by the provider.
    pub tokens_out: u64,
    /// True when `tokens_out` is an estimate, not provider-reported.
    pub tokens_out_estimated: bool,
    /// Money spent, in whole cents: provider-reported cost when the gateway
    /// reports one, otherwise `tokens × [PriceTable]` rounded up. `0` only
    /// when neither is known (the token caps stay the effective ones).
    pub usd_cents: u64,
}

/// A spend reservation held while one provider call is in flight.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Reservation {
    /// Store row id used to settle or release the reservation.
    pub id: i64,
    /// Agent the reservation belongs to.
    pub agent: String,
    /// Local day the reservation was taken on (`YYYY-MM-DD`).
    pub day: String,
    /// The amount reserved (the conservative upper estimate of the call).
    ///
    /// For a capped output direction this may be *clamped* below what the
    /// caller requested: the store reserves only what fits in the remaining
    /// headroom, and the caller must pass the clamped value to the provider
    /// as its completion cap (`max_tokens`).
    pub estimate: UsageTotals,
    /// Daily caps the reservation was admitted under.
    ///
    /// [`ReservationLedger::settle`] uses them to latch the day closed when a
    /// completed call reaches or crosses a cap (B-01R): a provider that
    /// ignores its completion cap can no longer cause unbounded further spend.
    pub caps: BudgetCaps,
    /// Identity of the turn that owns this call. Every `usage` row this
    /// reservation settles is stamped with it, so a receipt can sum its own
    /// turn's spend by identity instead of by a shared row-id window. `None`
    /// for callers that predate run-scoped attribution.
    pub run_id: Option<String>,
}

/// Outcome of an atomic [`ReservationLedger::try_reserve`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReserveOutcome {
    /// The call may proceed; the reservation is counted against the caps
    /// until it is settled or released.
    Reserved(Reservation),
    /// The call must not start; the denial carries the reached cap.
    Denied(Denial),
}

/// Atomic cap enforcement across concurrent turns.
///
/// `try_reserve` must read the day's recorded totals **and** the active
/// reservations, enforce `caps`, and insert the reservation in a single
/// store transaction (a `BEGIN IMMEDIATE` write). `settle` must delete the
/// reservation and insert the real usage rows in one transaction as well,
/// latching the day closed when the real usage reaches a cap.
///
/// This closes the check-then-spend race: a second turn racing the first
/// sees the first turn's reservation, and **its own reserve is part of the
/// admission test** (`recorded + active reservations + own reserve <= cap`),
/// so no admitted call's reservation crosses the remaining headroom. For a
/// capped output direction the requested reserve is clamped down to that
/// headroom instead of denying the call; callers pass the clamped value to
/// the provider as `max_tokens`.
///
/// Proven bound (B-01R):
///
/// - A provider that honors `max_tokens` and reports usage honestly cannot
///   settle above the daily cap: every admitted output reservation fits under
///   the cap, and each call settles at most its reservation. Concurrency does
///   not weaken this — N in-flight calls hold N reservations that jointly fit
///   under the cap.
/// - A provider that ignores `max_tokens` can settle the calls already in
///   flight above the cap. `settle` then latches the day closed; every later
///   `try_reserve` for that agent/day is denied ([`DenialReason::FailClosed`])
///   until the next local day, and no reservation is left behind. The
///   residual overshoot is exactly what those in-flight calls produced.
/// - Input usage is bounded only by the length estimate: a call can settle
///   above its input reservation by the estimate error. The cap still denies
///   the next call once the recorded total reaches it.
pub trait ReservationLedger {
    /// Atomically enforce `caps` for `agent`/`day` and reserve `estimate`.
    ///
    /// The caller's own reserve is part of the admission test. A capped
    /// output direction is clamped to the remaining headroom and the clamped
    /// reservation is returned; capped input (or money) that does not fit is
    /// denied instead.
    fn try_reserve(
        &self,
        agent: &str,
        day: &str,
        caps: &BudgetCaps,
        estimate: &UsageTotals,
    ) -> Result<ReserveOutcome, BudgetError>;

    /// Replace the reservation with the call's real usage (delete + insert
    /// in one transaction). Zero amounts insert nothing.
    ///
    /// When the real usage reaches or crosses a cap of `reservation.caps`,
    /// the day is also latched closed for `agent`: every later `try_reserve`
    /// on that day is denied until the next local day.
    fn settle(&self, reservation: &Reservation, actual: &UsageActual) -> Result<(), BudgetError>;

    /// Drop the reservation without recording usage (the call never
    /// completed, so no usage is known).
    fn release(&self, reservation: &Reservation) -> Result<(), BudgetError> {
        self.settle(reservation, &UsageActual::default())
    }
}

/// Audit a denial and return it, recording an audit failure on the denial
/// instead of un-denying the call.
pub fn audit_denial(audit: &dyn AuditSink, mut denial: Denial) -> Denial {
    if let Err(err) = audit.audit("budget.denied", &denial.audit_payload()) {
        denial.audit_error = Some(err.to_string());
    }
    denial
}

/// Enforces per-agent daily caps before provider calls.
///
/// `check` is deliberately synchronous: callers run it immediately before a
/// provider call, and a denial is audited as `budget.denied` before it is
/// returned. Ledger failures fail closed (deny) — an unreadable meter must
/// never turn into an unbounded spend.
///
/// This is the advisory, non-atomic path: between `check` and the actual
/// spend a concurrent turn can pass the same check, so N racing callers can
/// each spend after one shared check. The engine uses [`ReservationLedger`]
/// (atomic reserve-then-settle, own reserve included) instead; `check`
/// remains for callers that only need a read-only verdict.
///
/// Caps are enforced *between* calls: an agent just below its cap can still
/// make one call that crosses it. There is no bound on how far a single
/// call can cross the cap here — only [`ReservationLedger`] can bound the
/// output side, by passing the admitted reservation as the provider's
/// completion cap and latching the day closed on a crossing settle.
pub struct BudgetGuard<'a> {
    budgets: &'a Budgets,
    ledger: &'a dyn UsageLedger,
    audit: &'a dyn AuditSink,
    day: &'a str,
}

impl<'a> BudgetGuard<'a> {
    /// Build a guard for one local day.
    pub fn new(
        budgets: &'a Budgets,
        ledger: &'a dyn UsageLedger,
        audit: &'a dyn AuditSink,
        day: &'a str,
    ) -> Self {
        Self {
            budgets,
            ledger,
            audit,
            day,
        }
    }

    /// Decide whether `agent` may run. Denials are audited before returning.
    ///
    /// Only an explicit `unlimited = true` enforces nothing and allows
    /// without touching the ledger; absent or zero fields fall back to the
    /// conservative per-kind defaults (E-17).
    pub fn check(&self, agent: &str) -> Decision {
        let caps = self.budgets.caps_for(agent);
        if caps.is_unlimited() {
            return Decision::Allowed;
        }

        let totals = match self.ledger.day_totals(agent, self.day) {
            Ok(totals) => totals,
            Err(err) => {
                return self.deny(Denial {
                    agent: agent.to_string(),
                    day: self.day.to_string(),
                    reason: DenialReason::LedgerUnavailable {
                        message: err.to_string(),
                    },
                    audit_error: None,
                });
            }
        };

        // Provider kinds only: `ConnectorCalls` is metered by the connector
        // layer and is not carried by `UsageTotals`, so a connector cap can
        // never deny a provider call here.
        for kind in UsageKind::PROVIDER {
            let Some(limit) = caps.limit(kind) else {
                continue;
            };
            let spent = totals.get(kind);
            if spent >= limit {
                return self.deny(Denial {
                    agent: agent.to_string(),
                    day: self.day.to_string(),
                    reason: DenialReason::CapExceeded {
                        kind,
                        spent,
                        reserved: 0,
                        limit,
                    },
                    audit_error: None,
                });
            }
        }

        Decision::Allowed
    }

    /// Audit the denial and return it. An audit failure never un-denies.
    fn deny(&self, denial: Denial) -> Decision {
        Decision::Denied(audit_denial(self.audit, denial))
    }
}

