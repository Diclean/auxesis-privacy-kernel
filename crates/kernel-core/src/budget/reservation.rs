//! Atomic spend reservations held across one provider call.

use std::time::Duration;

use super::caps::BudgetCaps;
use super::denial::Denial;
use super::ledger::BudgetError;
use super::usage::UsageTotals;

/// How long an in-flight spend reservation stays active before it is treated
/// as abandoned (crashed process) and ignored by the cap check.
///
/// A reservation only covers one provider call, so this can be generous: the
/// only cost of a large TTL is that a crash mid-call keeps the reservation
/// counted until it expires.
///
/// It must also outlive the longest *stream* one call can run: the
/// OpenAI-compatible adapter bounds a stream at
/// `DEFAULT_TIMEOUT × STREAM_TOTAL_TIMEOUT_FACTOR` (120 s × 10 = 20 min with
/// the defaults), and a reservation that expires while the provider is still
/// generating lets a concurrent turn reserve the same headroom. 30
/// minutes leaves a 10-minute margin over that ceiling; the engine asserts
/// the relation in `the app's engine`.
pub const RESERVATION_TTL: Duration = Duration::from_secs(1800);

/// What one provider call actually consumed, per direction.
///
/// `*_estimated` marks a direction the provider did not report (the amount is
/// derived from text length and recorded with [`ESTIMATED_UNIT`](super::limits::ESTIMATED_UNIT)).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct UsageActual {
    /// Tokens sent to the provider.
    pub tokens_in: u64,
    /// True when `tokens_in` is an estimate, not provider-reported.
    pub tokens_in_estimated: bool,
    /// Tokens generated by the provider.
    pub tokens_out: u64,
    /// True when `tokens_out` is an estimate, not provider-reported.
    pub tokens_out_estimated: bool,
    /// Money spent, in whole cents: provider-reported cost when the gateway
    /// reports one, otherwise `tokens × [PriceTable]` rounded up. `0` only
    /// when neither is known (the token caps stay the effective ones).
    pub usd_cents: u64,
}

/// A spend reservation held while one provider call is in flight.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Reservation {
    /// Store row id used to settle or release the reservation.
    pub id: i64,
    /// Agent the reservation belongs to.
    pub agent: String,
    /// Local day the reservation was taken on (`YYYY-MM-DD`).
    pub day: String,
    /// The amount reserved (the conservative upper estimate of the call).
    ///
    /// For a capped output direction this may be *clamped* below what the
    /// caller requested: the store reserves only what fits in the remaining
    /// headroom, and the caller must pass the clamped value to the provider
    /// as its completion cap (`max_tokens`).
    pub estimate: UsageTotals,
    /// Daily caps the reservation was admitted under.
    ///
    /// [`ReservationLedger::settle`] uses them to latch the day closed when a
    /// completed call reaches or crosses a cap: a provider that
    /// ignores its completion cap can no longer cause unbounded further spend.
    pub caps: BudgetCaps,
    /// Identity of the turn that owns this call. Every `usage` row this
    /// reservation settles is stamped with it, so a receipt can sum its own
    /// turn's spend by identity instead of by a shared row-id window. `None`
    /// for callers that predate run-scoped attribution.
    pub run_id: Option<String>,
}

/// Outcome of an atomic [`ReservationLedger::try_reserve`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReserveOutcome {
    /// The call may proceed; the reservation is counted against the caps
    /// until it is settled or released.
    Reserved(Reservation),
    /// The call must not start; the denial carries the reached cap.
    Denied(Denial),
}

/// Atomic cap enforcement across concurrent turns.
///
/// `try_reserve` must read the day's recorded totals **and** the active
/// reservations, enforce `caps`, and insert the reservation in a single
/// store transaction (a `BEGIN IMMEDIATE` write). `settle` must delete the
/// reservation and insert the real usage rows in one transaction as well,
/// latching the day closed when the real usage reaches a cap.
///
/// This closes the check-then-spend race: a second turn racing the first
/// sees the first turn's reservation, and **its own reserve is part of the
/// admission test** (`recorded + active reservations + own reserve <= cap`),
/// so no admitted call's reservation crosses the remaining headroom. For a
/// capped output direction the requested reserve is clamped down to that
/// headroom instead of denying the call; callers pass the clamped value to
/// the provider as `max_tokens`.
///
/// Proven bound:
///
/// - A provider that honors `max_tokens` and reports usage honestly cannot
///   settle above the daily cap: every admitted output reservation fits under
///   the cap, and each call settles at most its reservation. Concurrency does
///   not weaken this — N in-flight calls hold N reservations that jointly fit
///   under the cap.
/// - A provider that ignores `max_tokens` can settle the calls already in
///   flight above the cap. `settle` then latches the day closed; every later
///   `try_reserve` for that agent/day is denied ([`DenialReason::FailClosed`](super::denial::DenialReason::FailClosed))
///   until the next local day, and no reservation is left behind. The
///   residual overshoot is exactly what those in-flight calls produced.
/// - Input usage is bounded only by the length estimate: a call can settle
///   above its input reservation by the estimate error. The cap still denies
///   the next call once the recorded total reaches it.
pub trait ReservationLedger {
    /// Atomically enforce `caps` for `agent`/`day` and reserve `estimate`.
    ///
    /// The caller's own reserve is part of the admission test. A capped
    /// output direction is clamped to the remaining headroom and the clamped
    /// reservation is returned; capped input (or money) that does not fit is
    /// denied instead.
    fn try_reserve(
        &self,
        agent: &str,
        day: &str,
        caps: &BudgetCaps,
        estimate: &UsageTotals,
    ) -> Result<ReserveOutcome, BudgetError>;

    /// Replace the reservation with the call's real usage (delete + insert
    /// in one transaction). Zero amounts insert nothing.
    ///
    /// When the real usage reaches or crosses a cap of `reservation.caps`,
    /// the day is also latched closed for `agent`: every later `try_reserve`
    /// on that day is denied until the next local day.
    fn settle(&self, reservation: &Reservation, actual: &UsageActual) -> Result<(), BudgetError>;

    /// Drop the reservation without recording usage (the call never
    /// completed, so no usage is known).
    fn release(&self, reservation: &Reservation) -> Result<(), BudgetError> {
        self.settle(reservation, &UsageActual::default())
    }
}
