/// Whether a folded single word is a [`COMMON_WORDS`] word.
pub(crate) fn is_common_word(folded: &str) -> bool {
    static COMMON: OnceLock<HashSet<String>> = OnceLock::new();
    COMMON
        .get_or_init(|| COMMON_WORDS.iter().copied().map(folded_text).collect())
        .contains(folded)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn common_words_are_listed_folded() {
        assert!(is_common_word(&folded_text("Rose")));
        assert!(is_common_word(&folded_text("Bon")));
        assert!(is_common_word(&folded_text("Blanc")));
        assert!(!is_common_word(&folded_text("Dupont")));
    }

    #[test]
    fn function_words_and_labels_are_closed_but_names_are_not() {
        for word in ["le", "De", "The", "Aan", "Feladó", "Кому", "من", "Objet"] {
            assert!(
                is_closed_word(&folded_text(word)),
                "{word} should be closed"
            );
        }
        for name in ["Will", "Mark", "Rose", "Pierre", "Jan", "Ben", "Ali", "Ana"] {
            assert!(
                !is_closed_word(&folded_text(name)),
                "{name} must stay a name"
            );
        }
    }
}
