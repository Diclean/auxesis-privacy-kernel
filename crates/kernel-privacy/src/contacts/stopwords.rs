/// Whether `folded` is one of the closed words. `folded` must be a folded
/// single token (see `fold`), as the variants are.
pub(crate) fn is_closed_word(folded: &str) -> bool {
    static CLOSED: OnceLock<HashSet<String>> = OnceLock::new();
    CLOSED
        .get_or_init(|| CLOSED_WORDS.iter().copied().map(folded_text).collect())
        .contains(folded)
}

