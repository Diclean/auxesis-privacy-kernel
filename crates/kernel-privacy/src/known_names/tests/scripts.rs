//! Names in non-Latin, caseless and no-space scripts.

use super::assert_all;

#[test]
fn non_latin_names_match_in_every_case() {
    assert_all(&[
        (
            "Сергей Иванов",
            &["СЕРГЕЙ ИВАНОВ звонил", "СЕРГЕЙ", "сергей иванов"],
        ),
        ("Иван Петров", &["ИВАН ПЕТРОВ"]),
        (
            "Νίκος Παπαδόπουλος",
            &["ΝΙΚΟΣ ΠΑΠΑΔΟΠΟΥΛΟΣ", "νίκος παπαδόπουλος", "Νικος"],
        ),
        ("Ηλίας Ευαγγέλου", &["ΗΛΙΑΣ ΕΥΑΓΓΕΛΟΥ", "ηλίας ευαγγέλου"]),
    ]);
}

#[test]
fn no_space_script_names_match_as_substrings() {
    assert_all(&[
        (
            "王伟",
            &[
                "王伟",
                "王伟来了",
                "我和王伟明天去北京",
                "Call 王伟 tomorrow",
            ],
        ),
        ("李小龙", &["李小龙说你好"]),
        ("田中太郎", &["田中太郎さんが来ました"]),
        ("田中 太郎", &["田中さんが来ました"]),
        ("さくら", &["さくらさんが来た"]),
        ("김민수", &["김민수가 왔어요"]),
        ("김 민수", &["김민수씨가", "민수야 안녕"]),
        ("สมชาย ใจดี", &["คุณสมชายโทรมา"]),
    ]);
}

#[test]
fn a_no_space_script_char_is_a_word_boundary() {
    assert_all(&[(
        "Camille Exemple",
        &[
            "明天和Camille开会",
            "Camilleさんに連絡",
            "Camille씨가 왔어요",
            "ส่งให้Camilleแล้ว",
        ],
    )]);
}

#[test]
fn attached_hebrew_and_arabic_prefixes() {
    assert_all(&[
        (
            "דוד כהן",
            &[
                "לדוד",
                "ודוד כהן הגיעו",
                "שדוד אמר",
                "מדוד",
                "בכהן",
                "הכהן",
                "ולדוד",
            ],
        ),
        ("יוסי לוי", &["ליוסי"]),
    ]);
}

#[test]
fn arabic_script_folding() {
    assert_all(&[
        ("محمد علي", &["علی آمد", "محـمد"]),
        ("علي", &["علی"]),
        ("كريم", &["کریم"]),
        ("فاطمة الزهراء", &["فاطمه آمد"]),
        ("عبدالله", &["اتصل عبد الله"]),
    ]);
}
